// 代码源、事件归属、正则分支与历史快照的本地 Mock 检查，不访问远端 Git。
import assert from 'node:assert/strict'
import { createServer } from 'vite'
import { effectScope, ref } from 'vue'
const server = await createServer({ server: { middlewareMode: true, hmr: false }, appType: 'custom' })
let count = 0
const check = (name, result) => { assert.ok(result, name); count++; console.log('PASS ' + name) }
const rejects = async (name, promise, pattern) => { await assert.rejects(promise, pattern); count++; console.log('PASS ' + name) }
const waitFor = async predicate => { for (let i = 0; i < 100; i++) { if (predicate()) return; await new Promise(resolve => setTimeout(resolve, 20)) } throw Error('等待状态超时') }
try {
  const api = await server.ssrLoadModule('/src/api/index.ts')
  const db = await server.ssrLoadModule('/src/mock/data.ts')
  const util = await server.ssrLoadModule('/src/utils/gitSources.ts')
  const { ciSourcesOf, sourceError, sourceMatches, ciGraphSource } = await server.ssrLoadModule('/src/utils/pipelineBuild.ts')
  const { gitMaterialsOf } = await server.ssrLoadModule('/src/utils/gitMaterials.ts')
  const { useBuildMaterials } = await server.ssrLoadModule('/src/composables/useBuildMaterials.ts')
  const appId = 'a-checkout'
  let cfg = await api.getConfig(appId)
  const material = gitMaterialsOf(cfg)[0]
  const second = { ...material, id: 'git-events-assets', repositoryUrl: 'https://github.com/acme/assets.git', checkoutPath: './assets' }
  check('单仓库展示两种分支与两种事件选项', util.sourceTypeOptions(material, 1, 'branch').length === 4)
  check('多仓库仅提供两种分支选项', util.sourceTypeOptions(material, 2, 'branch').length === 2)
  check('无事件目录的仓库只提供分支', util.sourceTypeOptions({ ...material, repositoryUrl: 'https://git.example.org/acme/repo.git' }, 1, 'branch').length === 2)
  check('SSH 与带认证的标准 URL 识别同一支持目录', util.supportsWebhook('git@github.com:acme/repo.git') && util.supportsWebhook('ssh://git@gitlab.com/acme/repo.git') && util.supportsWebhook('https://user:password@github.com/acme/repo.git'))
  check('相似域名不能使用支持目录', !util.supportsWebhook('https://github.com.example.org/acme/repo.git'))
  const tag = util.newSource({ gitMaterialId: material.id, type: 'regex', value: '^main$', selectedBranch: 'main' }, 'tag', 'main')
  check('切换 Tag 清除分支数据并初始化过滤', tag.value === '' && !tag.selectedBranch && tag.filters[0].key === 'tag')
  check('切回分支不保留事件过滤', !util.newSource(tag, 'branch', 'release/1.x').filters)
  check('Webhook 不参与分支匹配', !sourceMatches(tag, 'v1.4.0'))
  check('拒绝无效过滤正则', sourceError({ ...tag, filters: [{ key: 'tag', value: '[' }] }).includes('无效'))
  check('拒绝空过滤正则', sourceError({ ...tag, filters: [{ key: 'tag', value: '' }] }).includes('填写'))
  check('拒绝事件不支持的过滤键', sourceError({ ...tag, filters: [{ key: 'targetBranch', value: '.*' }] }).includes('支持'))
  check('拒绝重复过滤键', sourceError({ ...tag, filters: [tag.filters[0], tag.filters[0]] }).includes('重复'))
  check('拒绝未知源类型', sourceError({ ...tag, type: 'unknown' }).includes('有效'))
  let wf = await api.getWorkflow(appId)
  const original = wf.items.find(item => item.kind === 'ci')
  const pipelineId = 'ci-git-events'
  const saveSource = async source => {
    wf = await api.saveWorkflow(appId, { version: wf.version, items: [...wf.items.filter(item => item.id !== pipelineId), { ...original, id: pipelineId, definition: { ...original.definition, materials: [source] } }] }, cfg.version)
  }
  await saveSource(tag)
  const copy = ciSourcesOf(cfg, wf.items.find(item => item.id === pipelineId).definition)
  copy[0].filters[0].value = 'mutated'
  check('配置代码源含过滤条件独立副本', wf.items.find(item => item.id === pipelineId).definition.materials[0].filters[0].value === '^v.*')
  check('画布展示事件名称', ciGraphSource(cfg, wf.items.find(item => item.id === pipelineId).definition).branch === 'Tag Creation')
  const events = await api.listWebhookEvents(appId, pipelineId, material.id)
  check('接收列表含通过与失败的事件', events.length === 3 && events.filter(event => util.webhookMatches(tag, event)).length === 2)
  check('过滤结果记录接收值与正则', util.webhookFilterResults(tag, events[2])[0].received === 'experimental' && !util.webhookFilterResults(tag, events[2])[0].matches)
  check('事件 ID 可稳定回读', (await api.listWebhookEvents(appId, pipelineId, material.id))[0].id === events[0].id)
  events[0].payload.mutated = true
  check('事件 Payload 返回独立副本', !(await api.listWebhookEvents(appId, pipelineId, material.id))[0].payload.mutated)
  await rejects('拒绝读取其他应用的流水线事件', api.listWebhookEvents('a-notify', pipelineId, material.id), /不存在/)
  await rejects('拒绝读取其他仓库事件', api.listWebhookEvents(appId, pipelineId, second.id), /没有配置/)
  const pick = event => ({ gitMaterialId: material.id, branch: event.ref, commitSha: event.commit.sha, webhookEventId: event.id })
  const trigger = (event, changes = {}, version = wf.version) => api.triggerBuild(appId, event.commit.sha, cfg.version, pipelineId, event.ref, { workflowVersion: version, materials: [{ ...pick(event), ...changes }] })
  await rejects('拒绝缺少事件 ID 的 Tag 构建', trigger(events[0], { webhookEventId: undefined }), /事件不存在/)
  await rejects('拒绝不匹配过滤的事件', trigger(events[2]), /未通过/)
  await rejects('拒绝篡改事件提交', trigger(events[0], { commitSha: 'forged' }), /不一致/)
  await rejects('拒绝篡改事件引用', trigger(events[0], { branch: 'main' }), /不一致/)
  await rejects('拒绝过期事件选择版本', trigger(events[0], {}, wf.version - 1), /流水线已更新/)
  const build = await trigger(events[0])
  check('Tag 构建记录事件与源码快照', build.materials[0].sourceType === 'tag' && build.materials[0].branch === 'v1.4.0' && build.materials[0].webhookEvent.id === events[0].id)
  await api.cancelBuild(build.id)
  const pr = util.newSource(tag, 'pull_request', 'main')
  await saveSource(pr)
  check('修改过滤不改变已有构建快照', (await api.getBuild(build.id)).materials[0].webhookEvent.id === events[0].id)
  const retry = await api.retryBuild(build.id)
  check('重试沿用原事件与 Payload', JSON.stringify(retry.materials) === JSON.stringify(build.materials))
  await api.cancelBuild(retry.id)
  const prs = await api.listWebhookEvents(appId, pipelineId, material.id)
  check('PR 返回同提交但不同事件 ID 的更新通知', prs[0].commit.sha === prs[1].commit.sha && prs[0].id !== prs[1].id)
  check('PR 默认按目标分支筛选', prs.filter(event => util.webhookMatches(pr, event)).length === 2)
  check('不同事件类型不能复用过滤', !util.webhookMatches(tag, prs[0]))
  await rejects('切换源类型后不能使用旧 Tag 事件', trigger(events[0]), /未通过/)
  const prBuild = await trigger(prs[1])
  check('PR 构建保存选中的更新事件而非同 SHA 的其他事件', prBuild.materials[0].webhookEvent.id === prs[1].id)
  await api.cancelBuild(prBuild.id)
  const scope = effectScope()
  const visible = ref(true)
  const selection = scope.run(() => useBuildMaterials(visible, ref(appId), ref(pipelineId)))
  await waitFor(() => !selection.loading.value)
  selection.selectEvent(prs[0].id)
  selection.selectEvent(prs[1].id)
  check('选材按事件 ID 区分相同 SHA', selection.active.value.selectedEventId === prs[1].id && selection.selectedCount.value === 1)
  await selection.refresh(selection.active.value)
  check('刷新保留有效事件选择', selection.active.value.selectedEventId === prs[1].id)
  selection.selectEvent(prs[2].id)
  check('不允许选择未通过过滤的事件', selection.active.value.selectedEventId === prs[1].id)
  visible.value = false
  scope.stop()
  await rejects('Webhook 应用增加仓库前要求修改源类型', api.saveConfig(appId, { section: 'git', expectedVersion: cfg.version, gitMaterials: [material, second] }), /先将 Webhook/)
  check('添加仓库失败不改变配置版本与仓库', (await api.getConfig(appId)).version === cfg.version && gitMaterialsOf(await api.getConfig(appId)).length === 1)
  await saveSource({ gitMaterialId: material.id, type: 'regex', value: '^(main|release/1\\.x|missing)$' })
  await rejects('正则分支设置拒绝空分支', api.setPipelineBranches(appId, pipelineId, [{ gitMaterialId: material.id, branch: '' }], wf.version, cfg.version), /不匹配/)
  await rejects('正则分支设置拒绝不匹配分支', api.setPipelineBranches(appId, pipelineId, [{ gitMaterialId: material.id, branch: 'feature/other' }], wf.version, cfg.version), /不匹配/)
  await rejects('正则分支设置拒绝缺少仓库', api.setPipelineBranches(appId, pipelineId, [], wf.version, cfg.version), /唯一分支/)
  await rejects('正则分支设置拒绝重复仓库', api.setPipelineBranches(appId, pipelineId, [{ gitMaterialId: material.id, branch: 'main' }, { gitMaterialId: material.id, branch: 'main' }], wf.version, cfg.version), /唯一分支/)
  await rejects('正则分支设置检查应用版本', api.setPipelineBranches(appId, pipelineId, [{ gitMaterialId: material.id, branch: 'main' }], wf.version, cfg.version - 1), /已更新/)
  const previousVersion = wf.version
  wf = await api.setPipelineBranches(appId, pipelineId, [{ gitMaterialId: material.id, branch: ' release/1.x ' }], wf.version, cfg.version)
  const definition = wf.items.find(item => item.id === pipelineId).definition
  check('设置分支保留正则约束并更新流水线版本', definition.materials[0].value === '^(main|release/1\\.x|missing)$' && definition.materials[0].selectedBranch === 'release/1.x' && wf.version === previousVersion + 1)
  check('画布使用保存的具体分支', ciGraphSource(cfg, definition).branch === 'release/1.x')
  await rejects('正则分支设置拒绝过期流水线', api.setPipelineBranches(appId, pipelineId, [{ gitMaterialId: material.id, branch: 'main' }], previousVersion, cfg.version), /已更新/)
  const regexScope = effectScope()
  const regexSelection = regexScope.run(() => useBuildMaterials(ref(true), ref(appId), ref(pipelineId)))
  await waitFor(() => !regexSelection.loading.value)
  check('选材重新打开读取已保存分支', regexSelection.active.value.branch === 'release/1.x' && regexSelection.active.value.commits.length > 0)
  regexSelection.active.value.selectedSha = regexSelection.active.value.commits[0].sha
  await regexSelection.saveBranches([{ gitMaterialId: material.id, branch: 'main' }])
  check('改分支清除该仓库选择并读取新提交', regexSelection.active.value.branch === 'main' && !regexSelection.active.value.selectedSha && regexSelection.active.value.commits[0].sha === db.commits[0].sha)
  wf = await api.getWorkflow(appId)
  await regexSelection.saveBranches([{ gitMaterialId: material.id, branch: 'missing' }])
  check('匹配但不存在的分支返回空提交', regexSelection.active.value.branch === 'missing' && regexSelection.active.value.commits.length === 0)
  regexScope.stop()
  cfg = await api.saveConfig(appId, { section: 'git', expectedVersion: cfg.version, gitMaterials: [material, second] })
  wf = await api.getWorkflow(appId)
  const current = wf.items.find(item => item.id === pipelineId)
  await rejects('多仓库禁止保存 Webhook 代码源', api.saveWorkflow(appId, { version: wf.version, items: wf.items.map(item => item.id === pipelineId ? { ...item, definition: { ...current.definition, materials: [tag, { gitMaterialId: second.id, type: 'branch', value: 'main' }] } } : item) }), /多仓库/)
  check('新增仓库保留原正则与已选分支', current.definition.materials[0].selectedBranch === 'missing' && current.definition.materials.length === 2)
  const multi = { ...current, definition: { ...current.definition, materials: current.definition.materials.map(source => ({ ...source, type: 'regex', value: '^(main|release/1\\.x)$', selectedBranch: 'main' })) } }
  wf = await api.saveWorkflow(appId, { version: wf.version, items: wf.items.map(item => item.id === pipelineId ? multi : item) }, cfg.version)
  const selectedBranches = [{ gitMaterialId: material.id, branch: 'release/1.x' }, { gitMaterialId: second.id, branch: 'main' }]
  await rejects('多正则分支设置拒绝第二个不匹配的分支', api.setPipelineBranches(appId, pipelineId, [selectedBranches[0], { ...selectedBranches[1], branch: 'other' }], wf.version, cfg.version), /不匹配/)
  check('多正则验证失败不部分写入或增加版本', (await api.getWorkflow(appId)).version === wf.version && (await api.getWorkflow(appId)).items.find(item => item.id === pipelineId).definition.materials.every(source => source.selectedBranch === 'main'))
  wf = await api.setPipelineBranches(appId, pipelineId, selectedBranches, wf.version, cfg.version)
  check('多正则分支一次保存到对应仓库', wf.items.find(item => item.id === pipelineId).definition.materials.map(source => source.selectedBranch).join(',') === 'release/1.x,main')
  const multiScope = effectScope()
  const multiSelection = multiScope.run(() => useBuildMaterials(ref(true), ref(appId), ref(pipelineId)))
  await waitFor(() => !multiSelection.loading.value)
  multiSelection.states.value.forEach(state => { state.selectedSha = state.commits[0].sha; state.search = 'saved search' })
  const preservedSha = multiSelection.states.value[1].selectedSha
  await multiSelection.saveBranches([{ gitMaterialId: material.id, branch: 'main' }, selectedBranches[1]])
  check('设置多正则分支只清理变化仓库', !multiSelection.states.value[0].selectedSha && multiSelection.states.value[0].search === '' && multiSelection.states.value[1].selectedSha === preservedSha && multiSelection.states.value[1].search === 'saved search')
  multiScope.stop()
  const disposedScope = effectScope()
  const disposedSelection = disposedScope.run(() => useBuildMaterials(ref(true), ref(appId), ref(pipelineId)))
  disposedScope.stop()
  await new Promise(resolve => setTimeout(resolve, 400))
  check('选材卸载后忽略仍在途中的加载结果', disposedSelection.states.value.length === 0 && disposedSelection.config.value === null)
  console.log(`Completed ${count} Git source Mock checks`)
} finally { await server.close() }
