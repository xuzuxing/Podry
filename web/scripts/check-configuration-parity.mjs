function check(name, value) { assert.ok(value, name); checks.push(name); console.log('PASS ' + name) }
async function click(text, scope = 'document') {
  assert.ok(await evaluate(`(() => { const button = [...${scope}.querySelectorAll('button,a,.t-checkbox,.t-select-option')].find((item) => item.getClientRects().length && item.textContent.trim() === ${JSON.stringify(text)}); if (!button) return false; button.click(); return true })()`), '找不到操作：' + text)
  await delay(180)
}
async function input(selector, value) {
  if (selector.includes('.cm-content')) return cm.write(selector, value)
  await evaluate(`(() => { const item = document.querySelector(${JSON.stringify(selector)}); if (!item) throw Error('找不到输入框'); const prototype = item instanceof HTMLTextAreaElement ? HTMLTextAreaElement.prototype : HTMLInputElement.prototype; Object.getOwnPropertyDescriptor(prototype, 'value').set.call(item, ${JSON.stringify(value)}); item.dispatchEvent(new Event('input', { bubbles: true })); item.dispatchEvent(new Event('change', { bubbles: true })); })()`)
  await delay(100)
}
// 在同一页面会话中导航，使本地 Mock 修改可被回读。
async function go(path) {
  await evaluate(`document.querySelector('#app').__vue_app__.config.globalProperties.$router.push(${JSON.stringify(path)})`)
  await delay(700)
}
async function choose(selector, label) {
  await evaluate(`(() => { const select = document.querySelector(${JSON.stringify(selector)}); (select.querySelector('.t-input') ?? select).click() })()`)
  await until(`Array.from(document.querySelectorAll('.t-select-option')).some((item) => item.getClientRects().length && item.textContent.trim() === ${JSON.stringify(label)})`)
  await evaluate(`Array.from(document.querySelectorAll('.t-select-option')).find((item) => item.getClientRects().length && item.textContent.trim() === ${JSON.stringify(label)}).click()`)
  await delay(180)
}
